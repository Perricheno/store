export async function seed(db: DB) {
  const existing = await db.query("SELECT 1 FROM products LIMIT 1");
  if (existing.length) return;
  for (const [
    slug,
    category,
    gender,
    ru,
    kk,
    en,
    price,
    color,
    dru,
    dkk,
    den,
  ] of catalog) {
    const id = `demo-${slug}`;
    await db.query(
      "INSERT INTO products(id,slug,category,gender,brand,names,description,price,old_price,media,is_demo,published) VALUES($1,$2,$3,$4,$5,$6::jsonb,$7::jsonb,$8,$9,$10::jsonb,true,true) ON CONFLICT DO NOTHING",
      [
        id,
        slug,
        category,
        gender,
        "URBANMAG",
        JSON.stringify({ ru, kk, en }),
        JSON.stringify({ ru: dru, kk: dkk, en: den }),
        price,
        slug === "heavy-hoodie" ? 38900 : null,
        JSON.stringify([]),
      ],
    );
    const sizes =
      category === "accessories"
        ? ["ONE SIZE"]
        : category === "sneakers"
          ? ["37", "38", "39", "40", "41", "42", "43"]
          : ["XS", "S", "M", "L", "XL"];
    for (const size of sizes) {
      const vid = `${id}-${size.toLowerCase().replace(/ /g, "-")}`;
      await db.query(
        "INSERT INTO variants(id,product_id,size,color) VALUES($1,$2,$3,$4) ON CONFLICT DO NOTHING",
        [vid, id, size, color],
      );
      await db.query(
        "INSERT INTO inventory(variant_id,branch_id,quantity,reserved) VALUES($1,'main',8,0) ON CONFLICT DO NOTHING",
        [vid],
      );
    }
  }
}
