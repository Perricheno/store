/** Regenerate after category-icons changes: npx tsx scripts/generate-category-masks.ts */
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { writeFileSync } from "node:fs";
import { categoryIcons } from "../apps/web/src/lib/category-icons";

const masks = Object.fromEntries(
  Object.entries(categoryIcons).map(([category, Icon]) => {
    const svg = renderToStaticMarkup(
      createElement(Icon, {
        weight: "regular",
        color: "black",
        width: 256,
        height: 256,
      }),
    );
    return [category, `data:image/svg+xml,${encodeURIComponent(svg)}`];
  }),
);
writeFileSync(
  new URL("../apps/web/src/lib/category-masks.ts", import.meta.url),
  `// Generated by scripts/generate-category-masks.ts from category-icons.ts. Do not hand edit.\nexport const categoryMasks: Record<string, string> = ${JSON.stringify(masks, null, 2)};\n`,
);
