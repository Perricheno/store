export const walletCopy = (locale: Locale) => copy[locale];
export function walletError(code: string | undefined, locale: Locale) {
  const t = walletCopy(locale);
  if (code === "VALIDATION") return t.validation;
  if (code === "TOPUP_CHANGED") return t.changed;
  if (code === "WALLET_LIMIT") return t.limit;
  if (code === "INSUFFICIENT_FUNDS") return t.insufficient;
  if (code === "WALLET_FROZEN") return t.frozen;
  if (code === "WALLET_UNAVAILABLE") return t.walletUnavailable;
  if (code === "UNAUTHORIZED" || code === "PASSWORD_CHANGE_REQUIRED")
    return t.loginCheckout;
  return t.error;
}
